/**
 * Writes ios/Trueline/Entitlement.swift from core/src/entitlement.ts.
 *
 *     node --experimental-strip-types core/tools/gen-entitlement.mjs
 *     node --experimental-strip-types core/tools/gen-entitlement.mjs --check
 *
 * The gate has to be the same on both sides of this app. The web screens are
 * TypeScript and the subscription is Swift, and a list maintained twice is a
 * list that disagrees with itself -- in one direction somebody pays for
 * something they already had, and in the other they get something they did not.
 *
 * So the TypeScript is the source and the Swift is generated from it. `--check`
 * fails when the file on disk is not what this would write, which is what CI
 * and the pre-push hook run: a generated file that has gone stale is worse than
 * no generated file, because it looks maintained.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const out = join(root, 'ios', 'Trueline', 'Entitlement.swift');

const { FREE, PAID, FREE_ROOMS, TITLE, WHAT_IT_DOES } = await import(
  join(root, 'core', 'src', 'entitlement.ts')
);

const swiftString = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const caseName = (f) => f;

const all = [...FREE, ...PAID];

const body = `// Generated by core/tools/gen-entitlement.mjs from core/src/entitlement.ts.
// Do not edit by hand: the TypeScript is the source, because the same gate has
// to hold on both sides of this app and a list maintained twice disagrees with
// itself. Regenerate with:
//
//     node --experimental-strip-types core/tools/gen-entitlement.mjs

import Foundation

/// What is free, what is paid, and the sentence said when something is locked.
enum Entitlement {

    enum Feature: String, CaseIterable, Hashable {
${all.map((f) => `        case ${caseName(f)}`).join('\n')}
    }

    /// Everything anybody gets, forever, without an account.
    static let free: [Feature] = [${FREE.map((f) => `.${caseName(f)}`).join(', ')}]

    /// Everything a subscription unlocks, in the order it is explained.
    static let paid: [Feature] = [${PAID.map((f) => `.${caseName(f)}`).join(', ')}]

    /// How many rooms are kept without a subscription.
    static let freeRooms = ${FREE_ROOMS}

    static func isFree(_ feature: Feature) -> Bool { free.contains(feature) }

    static func allowed(_ feature: Feature, subscribed: Bool) -> Bool {
        subscribed || isFree(feature)
    }

    static func title(of feature: Feature) -> String {
        switch feature {
${all.map((f) => `        case .${caseName(f)}: return ${swiftString(TITLE[f])}`).join('\n')}
        }
    }

    /// What the thing does, never that it is locked.
    static func describe(_ feature: Feature) -> String {
        switch feature {
${all.map((f) => `        case .${caseName(f)}: return ${swiftString(WHAT_IT_DOES[f])}`).join('\n')}
        }
    }
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* not written yet */ }
  if (current !== body) {
    console.error('ios/Trueline/Entitlement.swift is not what core/src/entitlement.ts says.');
    console.error('Regenerate it:  node --experimental-strip-types core/tools/gen-entitlement.mjs');
    process.exit(1);
  }
  console.log('Entitlement.swift matches the TypeScript it is generated from');
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out}`);
}
